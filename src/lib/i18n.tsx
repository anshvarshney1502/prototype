export type Lang = "en" | "hi";
export type Key = keyof typeof en;
const dict = { en, hi };

const Ctx = createContext<{ lang: Lang; setLang: (l: Lang) => void }>({ lang: "en", setLang: () => {} });

export function LangProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");
  useEffect(() => {
    try { const s = localStorage.getItem("munshi_lang"); if (s === "hi" || s === "en") setLangState(s); } catch {}
  }, []);
  useEffect(() => { document.documentElement.lang = lang; }, [lang]);
  const setLang = useCallback((l: Lang) => { setLangState(l); try { localStorage.setItem("munshi_lang", l); } catch {} }, []);
  return <Ctx.Provider value={{ lang, setLang }}>{children}</Ctx.Provider>;
}

export function useLang() { return useContext(Ctx); }

// t("ivAdded", { f: "Prices" }) → "Added: Prices"
export function useT() {
  const { lang } = useContext(Ctx);
  return useCallback((k: Key, vars?: Record<string, string | number>) => {
    let s: string = dict[lang][k] ?? en[k];
    if (vars) for (const [a, b] of Object.entries(vars)) s = s.replaceAll(`{${a}}`, String(b));
    return s;
  }, [lang]);
}

export function LangToggle({ className = "" }: { className?: string }) {
  const { lang, setLang } = useLang();
  return (
    <div role="group" aria-label="Language / भाषा" className={`inline-flex rounded-full border border-line bg-surface p-0.5 text-[13.5px] font-medium ${className}`}>
      {(["en", "hi"] as const).map((l) => (
        <button key={l} type="button" aria-pressed={lang === l} onClick={() => setLang(l)}
          className={`h-8 min-w-11 px-3 rounded-full transition-colors cursor-pointer ${lang === l ? "bg-ink text-white" : "text-ink-2 hover:text-ink"}`}>
          {l === "en" ? "English" : "हिंदी"}
        </button>
      ))}
    </div>
  );
}
